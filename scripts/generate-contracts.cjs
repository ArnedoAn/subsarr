const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const sources = [
  'backend/src/contracts/api.ts',
  'backend/src/rename/rename.types.ts',
  'backend/src/quick-translate/quick-translate.types.ts',
];
const parts = sources.map((source) => {
  const content = fs.readFileSync(path.join(root, source), 'utf8');
  if (/^import\s/m.test(content)) {
    throw new Error(`${source} must contain only self-contained transport declarations`);
  }
  return `// Source: ${source}\n${content.trim()}\n`;
});
const generated = '// Generated by scripts/generate-contracts.cjs. Do not edit directly.\n\n' + parts.join('\n');
const destination = path.join(root, 'frontend/lib/types.ts');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(destination, 'utf8').replace(/\r\n/g, '\n') !== generated.replace(/\r\n/g, '\n')) {
    console.error('Transport contracts are stale. Run node scripts/generate-contracts.cjs');
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(destination, generated, 'utf8');
  console.log('Generated frontend/lib/types.ts from backend transport declarations');
}
